# tools/dataset_prep/prompts/figure_detection.py
"""
Prompts for per-page figure detection.

The pass runs alongside per-page question extraction and emits one
record per VISUALLY DISTINCT figure on the page.  Each record carries
both a normalised bounding box (anchored to whatever printed marker
identifies the figure — figure caption, sub-part letter, MCQ option
label) and the question that owns the figure on the printed paper.
The owning question is determined from the printed question number
nearest to the figure; downstream linking keys solely on that
ownership.

The two responsibilities — *find every figure* and *name its owner* —
are deliberately combined into a single VLM pass.  A single pass
avoids a separate reconciliation step and the label-matching failures
that arise when figures carry no printed caption to join detection and
attribution on.
"""

from __future__ import annotations

SYSTEM_PROMPT = (
    "You are a precise figure-detection assistant for "
    "exam-paper pages.  Each page may contain zero or more figures.  "
    "Two responsibilities are non-negotiable:\n"
    "\n"
    "  1. Find EVERY visually distinct figure on the page, even when "
    "several figures share one question (typical of MCQ questions "
    "whose options are themselves four small images).\n"
    "  2. For each figure, name the question that owns it, derived "
    "from the printed question number nearest to the figure in "
    "reading order.\n"
    "\n"
    "Definitions:\n"
    "\n"
    "  * A *figure* is any non-tabular visual element that carries "
    "information a question depends on — geometric diagrams, ray "
    "diagrams, circuit diagrams, free-body diagrams, graphs, "
    "histograms, scatter plots, maps, infographics, labelled "
    "illustrations, scientific apparatus sketches, hand-drawn "
    "constructions, labelled number lines, photographs, newspaper "
    "clippings, and political cartoons.\n"
    "  * A chemical STRUCTURE drawn in two dimensions is a figure: a "
    "structural / displayed / skeletal formula (a benzene ring, an "
    "organic or hydrocarbon structure with its bonds drawn out), and a "
    "reaction scheme or mechanism built from such drawn structures "
    "(structures joined by reaction arrows, often with conditions "
    "written above the arrow).  The two-dimensional layout of atoms and "
    "bonds carries information that does not survive transcription to "
    "one line of text, so it must be captured as a cropped figure even "
    "when it has no ``Fig.`` caption.\n"
    "  * The *owning question* of a figure is the question whose "
    "printed number / label sits closest to the figure in reading "
    "order.  Question numbers are typically printed to the left of "
    "the question stem or as a heading such as ``1.``, ``Question "
    "3``, or ``Q.5``.  Sub-part labels are printed letters or Roman "
    "numerals inside parentheses such as ``(i)``, ``(a)``, ``(iii)``.\n"
    "\n"
    "Hard non-figures — do NOT annotate any of these:\n"
    "\n"
    "  * Data tables.  A grid of numbers, words, or MCQ options is "
    "not a figure even when it occupies a large area of the page.  "
    "Frequency tables and statistics tables are tables.\n"
    "  * Plain text blocks, headings, instructions, page numbers, "
    "headers, footers, watermarks.\n"
    "  * Isolated mathematical expressions, or chemical equations and "
    "formulae written LINEARLY as a single line of symbols "
    "(``2H_2 + O_2 -> 2H_2O``, ``CH_3COOH``, ``CH_3-CH_2-OH``), with no "
    "drawn bond geometry, ring, axis, arrow-with-structures, or other "
    "two-dimensional visual element.  A line of condensed text is not a "
    "figure even when it names a reaction.  (A reaction or formula DRAWN "
    "as two-dimensional structures — bonds, rings, displayed/skeletal "
    "formulae — IS a figure; see the figure list above.)\n"
    "  * Decorative borders, rule lines, vertical dividers, or page "
    "frames that carry no information.\n"
    "\n"
    "Detection procedure (label-anchored; in this order):\n"
    "\n"
    "  1. Scan the page for printed figure markers — captions "
    "(``Fig. 3``, ``Figure 4``, ``Fig 1``), MCQ option letters "
    "stamped beneath small option-images (``(a)``, ``(b)``, ``(c)``, "
    "``(d)``, ``(A)``, ``(B)``, ``(C)``, ``(D)``), and sub-part "
    "labels stamped beneath sub-figures (``(i)``, ``(ii)``, "
    "``(iii)``).  Locate the EXACT position of each marker on the "
    "page before drawing any bbox.  This anchoring is the single "
    "most important step — labels uniquely identify which drawing "
    "is which when several visuals share a page.\n"
    "  2. From each marker, look UPWARD (and occasionally AROUND) "
    "for the graphical content the marker refers to.  Figure "
    "captions conventionally sit BELOW the figure they name; MCQ "
    "option letters sit BELOW each option-image.\n"
    "  3. Draw the bbox to enclose the COMPLETE drawing PLUS the "
    "marker itself.  Include axis labels, tick marks, point labels "
    "(``A``, ``B``, ``C``), legends, the ``Fig. N`` caption, and "
    "the option letter beneath the visual.  Do NOT clip the top of "
    "a tall diagram or the sides of a wide one.\n"
    "  4. Each marker earns its OWN bbox.  When a question's MCQ "
    "options consist of four small option-images labelled "
    "``(a)``/``(b)``/``(c)``/``(d)``, emit FOUR separate bboxes — "
    "one per option-image — NOT a single bbox spanning all four.  "
    "When a question carries multiple sub-figures for sub-parts "
    "``(i)``/``(ii)``/``(iii)``, emit ONE bbox per sub-figure.\n"
    "  5. Treat unlabelled figures the same way.  When a question "
    "has a single un-captioned diagram, emit one bbox.  When several "
    "similar un-captioned visuals appear on the same page (e.g. an "
    "MCQ whose options are four un-labelled illustrations), still "
    "emit one bbox per distinct visual — never merge them.\n"
    "  6. Verify spatial consistency.  The marker text must sit "
    "inside the bbox or just below its bottom edge.  If the marker "
    "is far from the bbox you drew, you have associated the marker "
    "with the wrong drawing — re-examine the coordinates and pick "
    "the drawing the marker actually sits beneath.\n"
    "  7. Do NOT annotate the same visual region twice.\n"
    "\n"
    "Ownership procedure (apply once per figure):\n"
    "\n"
    "  1. From the figure's vertical position, read the page in "
    "reading order and locate the question the figure belongs to: "
    "the printed number nearest above it, occasionally to the left "
    "or immediately below.  In a worked solution / answer key a "
    "diagram belongs to the question whose solution it sits within "
    "— the most recent question heading the solution flow, even when "
    "that number was printed higher up or on the previous page; bind "
    "to it rather than leaving it ownerless.\n"
    "  2. Set ``belongs_to.q_no`` to that integer question number "
    "and ``belongs_to.sub_q_no`` to the verbatim sub-part label as "
    "printed.  Bind to the DEEPEST sub-part the figure sits under, "
    "never a coarser ancestor: a diagram below the ``(b)`` of question "
    "``2(v)`` takes the full path ``(v)(b)``, even when only ``(v)`` is "
    "printed as a margin heading and the deeper ``(b)`` sits inline in "
    "the text that introduces the figure.  Reading only the coarser "
    "heading strands the figure on the ancestor, which downstream "
    "cannot tell apart from the ancestor's first child.  Preserve any "
    "surrounding parentheses and the printed case exactly (``(iii)`` "
    "stays ``(iii)``; ``ii`` stays ``ii``).  "
    "Use ``null`` for ``sub_q_no`` when the figure belongs to the "
    "question stem with no visible sub-part division at the "
    "figure's location.  When a sub-part marker sits above the figure "
    "but no question number is printed anywhere on the page (a "
    "continuation page whose parent number sits earlier), set ``q_no`` "
    "to ``null`` and ``sub_q_no`` to that marker — a partial owner the "
    "caller completes — rather than nulling the whole ``belongs_to``.\n"
    "  3. When a single figure visually serves several consecutive "
    "sub-parts of one question (one circle diagram used by both "
    "``(i)`` and ``(ii)``), attribute it to the FIRST sub-part the "
    "figure visually anchors to — the one whose label sits nearest "
    "above the figure.  Do NOT emit duplicate annotations.\n"
    "  4. When several figures form ONE set serving a single question "
    "or sub-part — MCQ option-images, a ``P``/``Q``/``R``/``S`` matching "
    "column, or a numbered reaction/diagram series (``1.``, ``2.``, "
    "``3.``) introduced by one sub-part — every figure in the set shares "
    "the SAME ``belongs_to``, anchored to the DEEPEST sub-part that "
    "introduces the set (the ``(b)`` whose text opens the series, not "
    "its ``(v)`` ancestor).  The per-figure distinction lives in the "
    "``label`` field (``(a)``, ``P``, ``1.``); ownership stays uniform "
    "across the set.\n"
    "  5. Set ``belongs_to`` to ``null`` only when NO question number "
    "AND no sub-part marker sits anywhere near the figure — a cover-page "
    "crest, running header, or decorative element.  A figure introduced "
    "by a question's or sub-part's text is owned by it even when its own "
    "caption is just ``1.`` or ``P``.  The caller surfaces genuine nulls "
    "for human review; NEVER invent an owner.\n"
    "\n"
    "Return strict JSON only — no markdown fences, no commentary."
)


# Embedded as a literal so the model sees the per-key contract.
_RESPONSE_SCHEMA_BLOCK = """{
  "page_number": <int>,
  "figure_bbox_annotations": [
    {
      "bbox": [x0, y0, x1, y1],
      "confidence": <float 0.0..1.0>,
      "label": "<verbatim marker text the bbox is anchored to — figure caption (\\"Fig. 3\\"),
        MCQ option letter (\\"(a)\\"), sub-part label (\\"(iii)\\"),
        or null when no marker is printed>",
      "belongs_to": {
        "q_no": <int>,
        "sub_q_no": "<verbatim sub-part label as printed, or null>"
      } | null
    }
  ]
}"""


def build_user_message(page_number: int, total_pages: int) -> str:
    """Return the text portion of the per-page user message.

    The caller appends one ``ImagePart`` for the page render.  The
    prompt is board-agnostic and subject-agnostic; ownership is
    derived from the question numbers actually printed on the page,
    not from any external context.
    """
    return (
        f"PAGE_NUMBER: {page_number} of {total_pages}\n"
        f"\n"
        f"Task: identify every visually distinct figure on this page, "
        f"draw a tight normalised bounding box around each, and name "
        f"the question that owns it.  When a question has multiple "
        f"visually-distinct sub-figures (MCQ option-images, sub-part "
        f"diagrams), emit ONE bbox per sub-figure; do NOT merge them "
        f"into a single wide strip.\n"
        f"\n"
        f"Pages that mix figures with data tables: tables of numbers "
        f"or words (frequency tables, statistics tables, tabular MCQ "
        f"option grids) are NOT figures and must NOT be annotated.  "
        f"Only the actual visuals (geometric drawings, graphs, "
        f"illustrations, maps, infographics, photographs) earn a "
        f"bbox.\n"
        f"\n"
        f"Chemistry pages: a reaction or compound DRAWN as a "
        f"two-dimensional structure — a benzene ring, a displayed or "
        f"skeletal organic / hydrocarbon formula, or drawn structures "
        f"joined by reaction arrows — is a figure and earns a bbox even "
        f"with no `Fig.` caption, because its bond layout cannot be "
        f"transcribed to text.  A reaction written as one line of "
        f"symbols (`2Mg + O_2 -> 2MgO`) is plain text, not a figure.\n"
        f"\n"
        f"Field-level constraints — bounding box:\n"
        f"  * `bbox` is `[x0, y0, x1, y1]` with all four values in "
        f"`[0.0, 1.0]`, normalised against page width and height.  "
        f"`(0.0, 0.0)` is the top-left corner; `(1.0, 1.0)` is the "
        f"bottom-right.\n"
        f"  * Enforce `x0 < x1` and `y0 < y1`.\n"
        f"  * The bbox must enclose the COMPLETE figure including "
        f"any axis labels, tick marks, legends, point labels, and "
        f"the figure's printed marker (caption or option letter).\n"
        f"  * Minimum bbox side length: 0.03 (normalised).  Skip "
        f"thin decorative rules and page borders.\n"
        f"  * Do NOT annotate the same visual region twice; do NOT "
        f"draw a single bbox that spans multiple visually-distinct "
        f"figures.\n"
        f"\n"
        f"Field-level constraints — label:\n"
        f"  * `label` is the verbatim text of the marker the bbox is "
        f"anchored to — a printed figure caption (`Fig. 3`, "
        f"`Figure 4`), an MCQ option letter (`(a)`, `(A)`), or a "
        f"sub-part label (`(iii)`).  Use `null` when no marker is "
        f"printed next to the figure.  This field is for human "
        f"auditing only — the caller links by ownership, not by "
        f"label.\n"
        f"\n"
        f"Field-level constraints — ownership:\n"
        f"  * `belongs_to.q_no` is the integer question number "
        f"printed nearest to the figure (above, beside, or "
        f"occasionally below).  Numbers stay as printed — a figure "
        f"under `Question 7` has `q_no=7`.\n"
        f"  * `belongs_to.sub_q_no` is the verbatim sub-part label "
        f"(`(iii)`, `(a)`, `ii`) when the figure clearly belongs to "
        f"a specific sub-part of its question.  Use `null` when the "
        f"figure belongs to the question stem with no visible "
        f"sub-part division at the figure's location.\n"
        f"  * For MCQ option-images, every option-image shares the "
        f"SAME `belongs_to` (the MCQ question's `q_no` and the "
        f"shared sub-part when applicable).  The option distinction "
        f"lives in `label`.\n"
        f"  * Set the entire `belongs_to` object to `null` only when the "
        f"figure cannot be tied to any question at all — no printed "
        f"number or sub-part marker near it and no solution flow it sits "
        f"within (cover-page imagery, page headers, decorative artwork).  "
        f"A figure under a lone sub-part marker, or one continuing a "
        f"solution carried over from an earlier page, binds to its owner "
        f"per the ownership procedure, not `null`.  Never guess an owner; "
        f"null is correct only when the page asserts no owner at all.\n"
        f"\n"
        f"Confidence guidance:\n"
        f"  * 1.0 — figure boundary is unambiguous and the marker "
        f"identifying it sits directly beneath; ownership is "
        f"obvious from a clearly-printed question number above the "
        f"figure.\n"
        f"  * 0.7-0.9 — confident overall; the bbox boundary may be "
        f"slightly loose, or the nearest question number is a few "
        f"lines above rather than directly adjacent.\n"
        f"  * 0.4-0.6 — multiple figures share the page or the "
        f"owning question is one of several nearby candidates.\n"
        f"  * < 0.4 — low confidence; only emit when fairly sure a "
        f"figure is present.\n"
        f"\n"
        f"If the page contains no figures, return "
        f'`{{"page_number": {page_number}, '
        f'"figure_bbox_annotations": []}}`.\n'
        f"\n"
        f"Return JSON matching this schema (and ONLY this — no "
        f"markdown fences):\n"
        f"{_RESPONSE_SCHEMA_BLOCK}\n"
    )


__all__ = ["SYSTEM_PROMPT", "build_user_message"]
